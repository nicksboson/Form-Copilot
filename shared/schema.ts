// shared/schema.ts: Zod schemas and TypeScript types for Form Copilot data contracts

import { z } from 'zod';

export const QuestionTypeSchema = z.enum([
  'text',
  'paragraph',
  'radio',
  'checkboxes',
  'dropdown',
  'linear_scale',
  'date',
  'time',
  'file_upload',
  'unknown',
]);

export type QuestionType = z.infer<typeof QuestionTypeSchema>;

export const QuestionSchema = z.object({
  id: z.string(),
  entryKey: z.string().optional(),
  title: z.string(),
  description: z.string().optional(),
  type: QuestionTypeSchema,
  required: z.boolean(),
  options: z.array(z.string()).optional(),
  pageIndex: z.number().int().nonnegative(),
  isBranching: z.boolean().optional(),
  value: z.union([z.string(), z.array(z.string())]).optional(),
});

export type Question = z.infer<typeof QuestionSchema>;

export const FormPageSchema = z.object({
  index: z.number().int().nonnegative(),
  title: z.string().optional(),
  description: z.string().optional(),
  questions: z.array(QuestionSchema),
});

export type FormPage = z.infer<typeof FormPageSchema>;

export const FormSnapshotSchema = z.object({
  formId: z.string().optional(),
  formTitle: z.string(),
  formDescription: z.string().optional(),
  mode: z.enum(['FULL', 'PARTIAL']),
  pages: z.array(FormPageSchema),
  warnings: z.array(z.string()),
  scannedAt: z.string(),
});

export type FormSnapshot = z.infer<typeof FormSnapshotSchema>;

// Summary response generated by the LLM
export const FormSummarySchema = z.object({
  purpose: z.string(),
  pageCount: z.number().int().nonnegative(),
  requiredQuestions: z.array(z.string()),
  requiredDocuments: z.array(z.string()),
  branching: z.string(),
  overviewHi: z.string(),
});

export type FormSummary = z.infer<typeof FormSummarySchema>;

// Option draft returned by LLM
export const ConversationOptionSchema = z.object({
  en: z.string(),
  hi: z.string(),
});

export type ConversationOption = z.infer<typeof ConversationOptionSchema>;

// Conversation reply schema: questionId, Hindi explanation, at most 3 options
export const ConversationReplySchema = z.object({
  questionId: z.string().nullable(),
  explanationHi: z.string(),
  options: z.array(ConversationOptionSchema).max(3),
});

export type ConversationReply = z.infer<typeof ConversationReplySchema>;

// Fill request and result
export const FillRequestSchema = z.object({
  questionId: z.string(),
  answer: z.union([z.string(), z.array(z.string())]),
});

export type FillRequest = z.infer<typeof FillRequestSchema>;

export const FillResultSchema = z.object({
  questionId: z.string(),
  success: z.boolean(),
  status: z.enum(['filled', 'already_filled', 'manual_required', 'not_found', 'error']),
  message: z.string(),
  readValue: z.union([z.string(), z.array(z.string())]).optional(),
});

export type FillResult = z.infer<typeof FillResultSchema>;

// Diagnostics data
export const DiagnosticsSchema = z.object({
  mode: z.enum(['FULL', 'PARTIAL']),
  pagesFound: z.number().int().nonnegative(),
  questionsFound: z.number().int().nonnegative(),
  warnings: z.array(z.string()),
  lastError: z.string().nullable(),
});

export type Diagnostics = z.infer<typeof DiagnosticsSchema>;
